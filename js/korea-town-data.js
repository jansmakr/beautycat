function getDistricts(state) {
    return KOREA_TOWN_DATA[state] ? Object.keys(KOREA_TOWN_DATA[state]) : [];
}

// 읍/면/동 목록 가져오기
function getTowns(state, district) {
    return KOREA_TOWN_DATA[state] && KOREA_TOWN_DATA[state][district] 
        ? KOREA_TOWN_DATA[state][district] 
        : [];
}

// 전체 읍면동 개수
function getTotalTownCount() {
    let count = 0;
    for (const state in KOREA_TOWN_DATA) {
        for (const district in KOREA_TOWN_DATA[state]) {
            count += KOREA_TOWN_DATA[state][district].length;
        }
    }
    return count;
}

